export function HelpPage() {
  const [query, setQuery] = useState('');
  const words = query
    .trim()
    .toLocaleLowerCase('ru-RU')
    .replaceAll('ё', 'е')
    .split(/\s+/)
    .filter(Boolean);
  const matching = articles.filter((article) => {
    const text =
      `${article.category} ${article.question} ${article.paragraphs.join(' ')}`
        .toLocaleLowerCase('ru-RU')
        .replaceAll('ё', 'е');
    return words.every((word) => text.includes(word));
  });
  return (
    <div className="help-page">
      <PageHeader
        eyebrow="Справка"
        title="Как работает админка"
        description="Метрики, проверки сервисов, жалобы, права и уведомления."
        actions={
          <Link className="button secondary" to="/admin/monitor">
            Открыть мониторинг
          </Link>
        }
      />
      <form
        className="card help-search"
        role="search"
        onSubmit={(event) => event.preventDefault()}
      >
        <label htmlFor="admin-help-search">Поиск по вопросам и ответам</label>
        <div>
          <input
            id="admin-help-search"
            type="search"
            value={query}
            placeholder="Например: доставка, p95, контекст"
            onChange={(event) => setQuery(event.target.value)}
          />
          {query && (
            <button
              className="button secondary"
              type="button"
              onClick={() => setQuery('')}
            >
              Сбросить поиск
            </button>
          )}
        </div>
        <p role="status">Найдено вопросов: {matching.length}</p>
      </form>
      {matching.length ? (
        <div className="help-articles">
          {matching.map((article) => (
            <details
              className="card help-article"
              key={article.id}
              open={words.length > 0}
            >
              <summary>
                <span className="section-label">{article.category}</span>
                <span>{article.question}</span>
              </summary>
              <div>
                {article.paragraphs.map((paragraph) => (
                  <p key={paragraph}>{paragraph}</p>
                ))}
              </div>
            </details>
          ))}
        </div>
      ) : (
        <section className="card help-empty">
          <h2>Ничего не найдено</h2>
          <p>Попробуйте другое слово или сбросьте поиск.</p>
        </section>
      )}
    </div>
  );
}
